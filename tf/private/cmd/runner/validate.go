package main

import (
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log"
	"os"
	"path/filepath"
)

// runValidate implements --command=validate: the TofuValidate build action of
// a tf_library, tf_deploy or tf_test. It stages the work tree as runTest
// does, in a temporary directory removed on exit, runs `tofu init` and
// `tofu validate` there and writes --stamp. extraArgs go to `tofu validate`.
func runValidate(extraArgs []string) error {
	if *stamp == "" {
		return errors.New("--stamp is required")
	}
	// Bazel passes paths relative to the exec root, and tofu runs elsewhere.
	paths := append([]*string{tofu, workTree, pluginDir, modulesManifest, stamp}, varFilePtrs()...)
	if *lockFile != "" {
		paths = append(paths, lockFile)
	}
	for _, p := range paths {
		abs, err := filepath.Abs(*p)
		if err != nil {
			return err
		}
		*p = abs
	}

	// Only linux-sandbox gives each action a fresh TMPDIR (issue #90).
	scratch, err := os.MkdirTemp("", "rules_tofu-validate-")
	if err != nil {
		return err
	}
	defer os.RemoveAll(scratch)
	s, err := stage(scratch)
	if err != nil {
		return err
	}

	// init's stdout is progress output; its errors go to stderr.
	if err := s.init(io.Discard); err != nil {
		if calls, readErr := hasModuleCalls(*modulesManifest); readErr == nil && calls {
			log.Print("modules are never fetched, so ignore any advice to run `tofu init`: each module call's source and version must match the tf_library in deps that provides it (its module_source and module_version).")
		}
		fetchedModuleAdvice()
		return err
	}

	args := append([]string{"validate"}, s.dirArgs...)
	for _, f := range *varFiles {
		args = append(args, "-var-file="+f)
	}
	args = append(args, extraArgs...)
	if err := runTofu(s.env, s.cwd, args...); err != nil {
		// tofu sets up no providers for an empty root module, whatever the
		// modules its test runs load require.
		if !s.hasConfig && *testDir != "" {
			root := *packageDir
			if root == "" {
				root = "the workspace root"
			}
			log.Printf("the root module, %s, has no configuration file, and `tofu init` installs no providers for one. If a provider is reported missing, give the root module a file whose `required_providers` names it.", root)
		}
		fetchedModuleAdvice()
		return fmt.Errorf("tofu validate: %w", err)
	}
	return os.WriteFile(*stamp, nil, 0o644)
}

// fetchedModuleAdvice says what to do about a library generated by tf_modules
// that fails validation.
func fetchedModuleAdvice() {
	if *fetchedModule != "" {
		log.Printf("fetched module %s failed validation. Declare a different version on its tf_modules.module tag in MODULE.bazel, or get it fixed upstream.", *fetchedModule)
	}
}

// hasModuleCalls reports whether the module manifest at path records any
// module call: an entry other than the root module's.
func hasModuleCalls(path string) (bool, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return false, err
	}
	var manifest struct {
		Modules []struct{ Key string }
	}
	if err := json.Unmarshal(data, &manifest); err != nil {
		return false, err
	}
	for _, m := range manifest.Modules {
		if m.Key != "" {
			return true, nil
		}
	}
	return false, nil
}
